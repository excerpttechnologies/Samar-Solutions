export function SocialLinks({ className, iconClassName }: { className?: string; iconClassName?: string }) {
  return (
    <ul className={cn('flex items-center gap-1', className)}>
      {socialLinks.map((link) => (
        <li key={link.id}>
          <a
            href={link.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={link.label}
            className={cn(
              'inline-flex size-11 items-center justify-center rounded-full text-white/75 transition-colors hover:bg-white/10 hover:text-[#f4c65e]',
              iconClassName,
            )}
          >
            <SocialIcon id={link.id} />
          </a>
        </li>
      ))}
    </ul>
  )
}
